/** Stores the acceptance. Returns false on failure so callers can ask again rather than assume it. */
export async function recordNdaAcceptance(payload: NdaAcceptancePayload): Promise<boolean> {
  try {
    const db = await getDb();
    await db.insert(schema.ndaAcceptances).values({
      userId: payload.userId,
      name: payload.name,
      email: payload.email,
      version: NDA_AGREEMENT_TEXT.version,
      language: payload.language,
      ip: payload.ip,
      userAgent: payload.userAgent,
      agreedAt: payload.agreedAt,
    });
    log.info("legal.nda_accepted", { userId: payload.userId, version: NDA_AGREEMENT_TEXT.version });
    return true;
  } catch (err) {
    log.error("legal.nda_record_failed", { error: (err as Error).name });
    return false;
  }
}

export async function hasAcceptedNda(userId: string): Promise<boolean> {
  const db = await getDb();
  const [row] = await db
    .select({ id: schema.ndaAcceptances.id })
    .from(schema.ndaAcceptances)
    .where(and(eq(schema.ndaAcceptances.userId, userId), eq(schema.ndaAcceptances.version, NDA_AGREEMENT_TEXT.version)))
    .limit(1);
  return Boolean(row);
}
