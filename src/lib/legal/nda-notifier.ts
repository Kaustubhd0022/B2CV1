/**
 * Dispatches the accepted NDA agreement details to legal@donvanzara.com
 * and writes an immutable audit record to the local dev outbox.
 */
export async function notifyLegalOfNdaAcceptance(payload: NdaAcceptancePayload): Promise<{ ok: boolean; reason?: string }> {
  const agreedAt = payload.agreedAt || new Date();
  const plainText = buildPlainText(payload, agreedAt);
  const html = buildHtml(payload, agreedAt);

  // 1. Always append to local audit outbox for compliance preservation
  try {
    await mkdir(path.dirname(LEGAL_OUTBOX), { recursive: true });
    await appendFile(
      LEGAL_OUTBOX,
      JSON.stringify({
        event: "nda_accepted",
        legalEmail: LEGAL_EMAIL_RECIPIENT,
        signer: {
          name: payload.name,
          email: payload.email,
          userId: payload.userId,
          ip: payload.ip,
          userAgent: payload.userAgent,
          language: payload.language,
        },
        agreement: NDA_AGREEMENT_TEXT,
        agreedAt: agreedAt.toISOString(),
      }) + "\n"
    );
  } catch (err) {
    log.warn("legal.outbox_write_error", { error: (err as Error).message });
  }

  // 2. Dispatch via Resend API if configured
  const resendApiKey = process.env.RESEND_API_KEY;
  const fromEmail = process.env.LEGAL_EMAIL_FROM || process.env.EMAIL_FROM || "TattvaCo Legal <onboarding@resend.dev>";

  if (resendApiKey) {
    try {
      const res = await fetch("https://api.resend.com/emails", {
        method: "POST",
        headers: {
          Authorization: `Bearer ${resendApiKey}`,
          "Content-Type": "application/json",
        },
        body: JSON.stringify({
          from: fromEmail,
          to: [LEGAL_EMAIL_RECIPIENT],
          reply_to: payload.email,
          subject: `[NDA Agreement] Cultural Explorer Sign-Up: ${payload.name || payload.email} (${payload.email})`,
          text: plainText,
          html,
        }),
        signal: AbortSignal.timeout(10_000),
      });

      if (!res.ok) {
        const errJson = await res.json().catch(() => ({}));
        const errMsg = String(errJson.message || "");

        // If in Resend sandbox mode (domain not yet verified at resend.com/domains),
        // deliver to the verified owner address so no notification is dropped.
        const matchOwner = errMsg.match(/testing emails to your own email address \(([^)]+)\)/);
        if (res.status === 403 && matchOwner && matchOwner[1]) {
          const fallbackOwner = matchOwner[1];
          const fallbackRes = await fetch("https://api.resend.com/emails", {
            method: "POST",
            headers: {
              Authorization: `Bearer ${resendApiKey}`,
              "Content-Type": "application/json",
            },
            body: JSON.stringify({
              from: "onboarding@resend.dev",
              to: [fallbackOwner],
              reply_to: payload.email,
              subject: `[FORWARD TO ${LEGAL_EMAIL_RECIPIENT}] [NDA Agreement] Sign-Up: ${payload.name || payload.email}`,
              text: `[NOTE: Resend is currently in sandbox mode. Once your domain is verified at resend.com/domains, emails will deliver directly to ${LEGAL_EMAIL_RECIPIENT}.]\n\n` + plainText,
              html: `<div style="background:#fef3c7;border:1px solid #f59e0b;padding:12px;border-radius:8px;margin-bottom:16px;font-size:12px;color:#92400e;"><strong>Resend Sandbox Notice:</strong> Delivered to your verified account (${fallbackOwner}) pending domain verification at <a href="https://resend.com/domains">resend.com/domains</a>. Intended recipient: <strong>${LEGAL_EMAIL_RECIPIENT}</strong>.</div>` + html,
            }),
            signal: AbortSignal.timeout(10_000),
          });

          if (fallbackRes.ok) {
            log.info("legal.email_dispatched_sandbox_fallback", {
              fallbackTo: fallbackOwner,
              intendedTo: LEGAL_EMAIL_RECIPIENT,
              signer: payload.email,
            });
            return { ok: true, reason: "delivered_to_owner_sandbox" };
          }
        }

        log.warn("legal.email_provider_error", { status: res.status, err: errMsg });
        return { ok: false, reason: "provider_error" };
      }

      log.info("legal.email_dispatched", {
        to: LEGAL_EMAIL_RECIPIENT,
        signer: payload.email,
      });
      return { ok: true };
    } catch (err) {
      log.warn("legal.email_dispatch_failed", { error: (err as Error).message });
      return { ok: false, reason: "network_error" };
    }
  }

  log.info("legal.email_recorded_outbox", {
    to: LEGAL_EMAIL_RECIPIENT,
    signer: payload.email,
    note: "RESEND_API_KEY not configured; recorded in dev outbox",
  });
  return { ok: true, reason: "recorded_locally" };
}
