function formatIST(date: Date): string {
  try {
    return new Intl.DateTimeFormat("en-IN", {
      timeZone: "Asia/Kolkata",
      dateStyle: "full",
      timeStyle: "long",
    }).format(date);
  } catch {
    return date.toISOString();
  }
}

